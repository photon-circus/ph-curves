fn emit_curve(
    out: &mut String,
    name: &str,
    const_name: &str,
    def: &CurveDef,
    data: &CurveData,
    value_type: &str,
    lut_size: usize,
) {
    let name_doc = markdown_debug(name);
    // Forward LUT.
    out.push_str(&format!(
        "static {const_name}_FWD: [{vt}; {lut_size}] = {arr};\n",
        vt = value_type,
        arr = format_array(&data.fwd),
    ));

    // Inverse LUT (monotonic only).
    if let Some(inv) = &data.inv {
        out.push_str(&format!(
            "static {const_name}_INV: [{vt}; {lut_size}] = {arr};\n",
            vt = value_type,
            arr = format_array(inv),
        ));
    }

    // Public constant. Markdown-safe Debug formatting keeps TOML text inside
    // the generated `///` comment without creating rustdoc constructs.
    if def.monotonic {
        out.push_str(&format!(
            "/// {name_doc} \u{2014} monotonic curve.\n\
             pub const {const_name}: MonoLut = \
             MonoLut::new(&{const_name}_FWD, &{const_name}_INV);\n\n",
        ));
    } else {
        out.push_str(&format!(
            "/// {name_doc} \u{2014} curve (non-monotonic).\n\
             pub const {const_name}: Lut = \
             Lut::new(&{const_name}_FWD, None);\n\n",
        ));
    }
}

fn emit_transfer(
    out: &mut String,
    name: &str,
    const_name: &str,
    def: &TransferDef,
    data: &TransferData,
    origin: Option<&FamilyMemberOrigin>,
) {
    let knot_count = data.inputs.len();
    let direction = match data.direction {
        crate::MonotonicDirection::Increasing => "MonotonicDirection::Increasing",
        crate::MonotonicDirection::Decreasing => "MonotonicDirection::Decreasing",
    };
    let domain_min = data.inputs[0];
    let domain_max = *data.inputs.last().unwrap();
    let name_doc = markdown_debug(name);
    let representation_doc = markdown_debug(&data.representation);
    let input_unit_doc = markdown_debug(&def.input_unit);
    let output_unit_doc = markdown_debug(&def.output_unit);

    out.push_str(&format!(
        "#[rustfmt::skip]\n\
         static {const_name}_INPUTS: [u16; {knot_count}] = {inputs};\n",
        inputs = format_u16_array(&data.inputs),
    ));
    out.push_str(&format!(
        "#[rustfmt::skip]\n\
         static {const_name}_OUTPUTS: [i32; {knot_count}] = {outputs};\n",
        outputs = format_i32_array(&data.outputs),
    ));
    let guard_docs = match def.observation_guard.as_ref() {
        Some(guard) => {
            let behavior = match guard.behavior {
                super::transfer::ObservationGuardBehaviorDef::Error => "Error",
                super::transfer::ObservationGuardBehaviorDef::Clamp => "Clamp",
            };
            let classification = match &data.guard_provenance {
                Some(citation) => format!(
                    "/// Classification of this code as saturation is cited from {} and applied as declared policy, not inferred from the integer value.\n",
                    citation.rustdoc_clause()
                ),
                None => "/// Classification of this code as saturation is declared consumer/device policy, not inferred from the integer value.\n".into(),
            };
            format!(
                "/// Observation guard: code {} with {behavior} behavior.\n{classification}",
                guard.code
            )
        }
        None => "/// Observation guard: none.\n".into(),
    };
    let construction = match def.observation_guard.as_ref() {
        Some(guard) => format!(
            "PiecewiseLinearTransfer::new(&{const_name}_INPUTS, &{const_name}_OUTPUTS, {direction})\n\
                 .with_boundaries({below}, {above})\n\
                 .with_observation_guard({code}, {behavior});\n",
            below = def.below.rust_name(),
            above = def.above.rust_name(),
            code = guard.code,
            behavior = guard.behavior.rust_name(),
        ),
        None => format!(
            "PiecewiseLinearTransfer::new(&{const_name}_INPUTS, &{const_name}_OUTPUTS, {direction})\n\
                 .with_boundaries({below}, {above});\n",
            below = def.below.rust_name(),
            above = def.above.rust_name(),
        ),
    };
    let provenance_docs = match &data.provenance {
        Some(citation) => format!("/// Source provenance: {}.\n", citation.rustdoc_clause()),
        None => "/// Source provenance: none declared.\n".into(),
    };
    let policy_docs = format!(
        "/// Generation policy: {}.\n",
        def.policy().rustdoc_clause()
    );
    let identity_docs = family_identity_docs(origin);
    // Markdown-safe Debug formatting prevents TOML-derived text from breaking
    // the comment or becoming links, emphasis, code, or raw HTML.
    out.push_str(&format!(
        "{identity_docs}\
         /// {name_doc} sparse physical transfer function.\n\
         ///\n\
         {provenance_docs}\
         /// Representation: {representation_doc}.\n\
         {policy_docs}\
         /// Domain: {domain_min}..={domain_max} {input_unit_doc}; output: {output_unit_doc} x {output_scale}.\n\
         /// Knots: {knot_count} ({payload} bytes array payload).\n\
         /// Exhaustive numerical error: requested <= {requested}, achieved {achieved:.6} output quanta\n\
         /// (conservative metadata bound {achieved_bound}) at input {worst}.\n\
         /// This is table/quantization error against the configured ideal source, not total sensor accuracy.\n\
         {guard_docs}\
         #[rustfmt::skip]\n\
         pub const {const_name}: PiecewiseLinearTransfer<{knot_count}> =\n\
             {construction}",
        output_scale = def.output_scale,
        payload = knot_count * TABLE_BYTES_PER_KNOT,
        requested = def.max_interpolation_error,
        achieved = data.achieved_max_error_exact,
        achieved_bound = data.achieved_max_error,
        worst = data.worst_case_input,
    ));
    let (range_min, range_max) = output_range(&data.outputs);
    let flat_segment_count = data
        .outputs
        .windows(2)
        .filter(|pair| pair[0] == pair[1])
        .count();
    let strictly_monotonic = flat_segment_count == 0;
    let achieved_max_inverse_code_error =
        super::transfer::measure_inverse_code_error(&data.inputs, &data.outputs, data.direction);

    out.push_str(&format!(
        "/// Metadata for [`{const_name}`].\n\
         pub const {const_name}_METADATA: TransferMetadata = TransferMetadata {{\n\
         \x20   input_unit: {input_unit:?},\n\
         \x20   output_unit: {output_unit:?},\n\
         \x20   output_scale: {output_scale},\n\
         \x20   domain_min: {domain_min},\n\
         \x20   domain_max: {domain_max},\n\
         \x20   range_min: {range_min},\n\
         \x20   range_max: {range_max},\n\
         \x20   direction: {direction},\n\
         \x20   knot_count: {knot_count},\n\
         \x20   strictly_monotonic: {strictly_monotonic},\n\
         \x20   flat_segment_count: {flat_segment_count},\n\
         \x20   requested_max_error: {requested},\n\
         \x20   achieved_max_error: {achieved},\n\
         \x20   worst_case_input: {worst},\n\
         \x20   achieved_max_inverse_code_error: {inverse_error},\n\
         }};\n",
        input_unit = def.input_unit,
        output_unit = def.output_unit,
        output_scale = def.output_scale,
        requested = def.max_interpolation_error,
        achieved = data.achieved_max_error,
        worst = data.worst_case_input,
        inverse_error = achieved_max_inverse_code_error,
    ));
    let guard_metadata = match def.observation_guard.as_ref() {
        Some(guard) => format!(
            "Some(ObservationGuardMetadata {{\n\
         \x20   code: {},\n\
         \x20   behavior: {},\n\
         }})",
            guard.code,
            guard.behavior.rust_name()
        ),
        None => "None".into(),
    };
    let guard_companion_docs = match &data.guard_provenance {
        Some(citation) => format!(
            "/// Optional observation-code guard for [`{const_name}`].\n\
             ///\n\
             /// Classification of a code as saturation is cited from {} and applied as declared policy,\n\
             /// not inferred from the integer value. The runtime getter and this constant agree.\n",
            citation.rustdoc_clause()
        ),
        None => format!(
            "/// Optional observation-code guard for [`{const_name}`].\n\
             ///\n\
             /// Classification of a code as saturation is declared consumer/device policy,\n\
             /// not inferred from the integer value. The runtime getter and this constant agree.\n"
        ),
    };
    out.push_str(&format!(
        "{guard_companion_docs}\
         pub const {const_name}_OBSERVATION_GUARD: Option<ObservationGuardMetadata> = {guard_metadata};\n\n"
    ));
}

fn family_identity_docs(origin: Option<&FamilyMemberOrigin>) -> String {
    let Some(origin) = origin else {
        return String::new();
    };
    let family_doc = markdown_debug(&origin.family);
    let selectors = origin
        .selectors
        .iter()
        .map(|(key, value)| {
            let key_doc = markdown_debug(key);
            let value_doc = match value {
                SelectorValue::String(text) => markdown_debug(text),
                SelectorValue::Integer(int) => int.to_string(),
            };
            format!("{key_doc} = {value_doc}")
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("/// Family: {family_doc}.\n/// Selectors: {selectors}.\n")
}

pub(crate) fn emitted_const_names(
    curves: &[(&String, &CurveDef)],
    transfers: &[(&String, &TransferDef)],
) -> Result<BTreeMap<String, String>, String> {
    let mut names = BTreeMap::new();
    let mut base_sources = BTreeMap::new();

    for name in curves
        .iter()
        .map(|(name, _)| *name)
        .chain(transfers.iter().map(|(name, _)| *name))
    {
        let const_name = to_const_name(name)?;
        if let Some(previous) = base_sources.insert(const_name.clone(), name.as_str()) {
            return Err(format!(
                "names `{previous}` and `{name}` both normalize to Rust identifier \
                 `{const_name}`; rename one entry"
            ));
        }
        names.insert(name.clone(), const_name);
    }

    let mut emitted_sources = BTreeMap::new();
    for (name, def) in curves {
        let const_name = &names[*name];
        let mut identifiers = vec![const_name.clone(), format!("{const_name}_FWD")];
        if def.monotonic {
            identifiers.push(format!("{const_name}_INV"));
        }
        reserve_identifiers(name, identifiers, &mut emitted_sources)?;
    }
    for (name, _) in transfers {
        let const_name = &names[*name];
        reserve_identifiers(
            name,
            [
                const_name.clone(),
                format!("{const_name}_INPUTS"),
                format!("{const_name}_OUTPUTS"),
                format!("{const_name}_METADATA"),
                format!("{const_name}_OBSERVATION_GUARD"),
            ],
            &mut emitted_sources,
        )?;
    }

    Ok(names)
}

fn reserve_identifiers<'a>(
    name: &'a str,
    identifiers: impl IntoIterator<Item = String>,
    emitted_sources: &mut BTreeMap<String, &'a str>,
) -> Result<(), String> {
    for identifier in identifiers {
        if let Some(previous) = emitted_sources.insert(identifier.clone(), name) {
            return Err(format!(
                "names `{previous}` and `{name}` generate duplicate Rust identifier \
                 `{identifier}`; rename one entry"
            ));
        }
    }
    Ok(())
}

pub(crate) fn to_const_name(name: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut prev_underscore = false;
    let mut has_alphanumeric = false;
    for ch in name.chars() {
        let next = if ch.is_ascii_alphanumeric() {
            has_alphanumeric = true;
            ch.to_ascii_uppercase()
        } else {
            '_'
        };
        if next == '_' {
            if !prev_underscore {
                out.push('_');
                prev_underscore = true;
            }
        } else {
            out.push(next);
            prev_underscore = false;
        }
    }
    if !has_alphanumeric {
        return Err(format!(
            "name `{name}` cannot be normalized to a Rust identifier; \
             include at least one ASCII letter or digit"
        ));
    }
    if out.as_bytes()[0].is_ascii_digit() {
        out.insert_str(0, "CURVE_");
    }
    Ok(out)
}

fn format_array(values: &[u32]) -> String {
    let mut out = String::from("[");
    for (idx, value) in values.iter().enumerate() {
        if idx > 0 {
            out.push_str(", ");
        }
        out.push_str(&value.to_string());
    }
    out.push(']');
    out
}

fn format_u16_array(values: &[u16]) -> String {
    format_values(values)
}

fn format_i32_array(values: &[i32]) -> String {
    format_values(values)
}

fn format_values<T: core::fmt::Display>(values: &[T]) -> String {
    let mut out = String::from("[");
    for (idx, value) in values.iter().enumerate() {
        if idx > 0 {
            out.push_str(", ");
        }
        out.push_str(&value.to_string());
    }
    out.push(']');
    out
}

