/// Render all curves and transfers as a complete Rust source string.
pub fn generate(
    curves_file: &DefinitionsFile,
    value_type: &str,
    lut_size: usize,
) -> Result<String, String> {
    Ok(generate_with_report(curves_file, value_type, lut_size)?.source)
}

/// Render source and the host audit report. Family aggregate budgets fail here.
pub fn generate_with_report(
    curves_file: &DefinitionsFile,
    value_type: &str,
    lut_size: usize,
) -> Result<GenerationResult, String> {
    let resolved = curves_file.resolved_transfers()?;
    let mut curves: Vec<(&String, &CurveDef)> = curves_file.curves.iter().collect();
    curves.sort_by_key(|(name, _)| *name);
    let mut transfers: Vec<(&String, &ResolvedTransfer)> = resolved.iter().collect();
    transfers.sort_by_key(|(name, _)| *name);
    let transfer_defs: Vec<(&String, &TransferDef)> = transfers
        .iter()
        .map(|(name, resolved)| (*name, &resolved.def))
        .collect();

    let const_names = emitted_const_names(&curves, &transfer_defs)?;

    let mut out = String::new();
    out.push_str("// Auto-generated by ph-curves-gen. Do not edit.\n\n");
    if !curves_file.curves.is_empty() {
        out.push_str("use ph_curves::{CurveLut, MonotonicCurveLut};\n\n");
    }
    if !resolved.is_empty() {
        let any_guard = resolved
            .values()
            .any(|resolved| resolved.def.observation_guard.is_some());
        if any_guard {
            out.push_str(
                "use ph_curves::{BoundaryBehavior, MonotonicDirection, ObservationGuardBehavior, \
                 ObservationGuardMetadata, PiecewiseLinearTransfer, TransferMetadata};\n\n",
            );
        } else {
            out.push_str(
                "use ph_curves::{BoundaryBehavior, MonotonicDirection, ObservationGuardMetadata, \
                 PiecewiseLinearTransfer, TransferMetadata};\n\n",
            );
        }
    }

    if !curves_file.curves.is_empty() {
        // Type aliases for convenience.
        out.push_str(&format!(
            "type Lut = CurveLut<{value_type}, {value_type}, {lut_size}>;\n",
        ));
        out.push_str(&format!(
            "type MonoLut = MonotonicCurveLut<{value_type}, {value_type}, {lut_size}>;\n\n",
        ));
    }

    for (name, def) in &curves {
        let data = super::curve::build(name, def, lut_size)?;
        let const_name = &const_names[*name];
        emit_curve(&mut out, name, const_name, def, &data, value_type, lut_size);
    }

    let mut transfer_reports = Vec::new();
    for (name, resolved) in &transfers {
        let overlay = curves_file.overlays.get(*name);
        let effective = overlay
            .map(|overlay| {
                overlay
                    .effective_def(&resolved.def)
                    .map_err(|error| format!("transfer `{name}`: {error}"))
            })
            .transpose()?;
        let def = effective.as_ref().unwrap_or(&resolved.def);
        let data = if let Some(overlay) = overlay {
            super::transfer::build_with_source(name, def, Some(overlay.source()))?
        } else {
            super::transfer::build(name, def)?
        };
        let const_name = &const_names[*name];
        transfer_reports.push(transfer_report(
            name,
            const_name,
            def,
            &data,
            resolved.origin.as_ref(),
        ));
        emit_transfer(
            &mut out,
            name,
            const_name,
            def,
            &data,
            resolved.origin.as_ref(),
        );
    }

    let report = assemble_report(
        transfer_reports,
        &curves_file.transfer_families,
        &curves_file.gaps,
    )?;
    enforce_family_budgets(&curves_file.transfer_families, &report)?;

    // Emitters leave a blank line after each item so adjacent definitions stay
    // readable. Normalize the complete file separately so generated fixtures
    // end with the conventional single newline, never a blank line at EOF.
    out.truncate(out.trim_end_matches('\n').len());
    out.push('\n');

    Ok(GenerationResult {
        source: out,
        report,
    })
}

fn transfer_report(
    name: &str,
    const_name: &str,
    def: &TransferDef,
    data: &TransferData,
    origin: Option<&FamilyMemberOrigin>,
) -> TransferReport {
    let knot_count = data.inputs.len();
    let domain_min = data.inputs[0];
    let domain_max = *data.inputs.last().expect("fitter requires two knots");
    let (range_min, range_max) = output_range(&data.outputs);
    TransferReport {
        family: origin.map(|origin| origin.family.clone()),
        selectors: origin
            .map(|origin| origin.selectors.clone())
            .unwrap_or_default(),
        table_name: name.to_string(),
        symbol: const_name.to_string(),
        metadata_symbol: format!("{const_name}_METADATA"),
        observation_guard_symbol: format!("{const_name}_OBSERVATION_GUARD"),
        domain_min,
        domain_max,
        range_min,
        range_max,
        requested_max_error: def.max_interpolation_error,
        achieved_max_error: data.achieved_max_error,
        worst_case_input: data.worst_case_input,
        knot_count,
        table_bytes: knot_count * TABLE_BYTES_PER_KNOT,
        generation_path: data.generation_path,
        provenance: data.provenance.clone(),
        observation_guard_provenance: data.guard_provenance.clone(),
        policy: def.policy(),
        observation_guard: def
            .observation_guard
            .as_ref()
            .map(observation_guard_metadata),
    }
}

fn output_range(outputs: &[i32]) -> (i32, i32) {
    let first = outputs[0];
    let last = *outputs.last().expect("fitter requires two knots");
    if first <= last {
        (first, last)
    } else {
        (last, first)
    }
}

fn observation_guard_metadata(guard: &ObservationGuardDef) -> ObservationGuardMetadata {
    ObservationGuardMetadata {
        code: guard.code,
        behavior: match guard.behavior {
            ObservationGuardBehaviorDef::Error => ObservationGuardBehavior::Error,
            ObservationGuardBehaviorDef::Clamp => ObservationGuardBehavior::Clamp,
        },
    }
}

