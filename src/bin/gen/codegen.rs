//! Rust source-code generation from built curve data.

use super::curve::{CurveData, CurveDef, CurvesFile};

/// Render all curves as a complete Rust source string.
pub fn generate(curves_file: &CurvesFile, value_type: &str, lut_size: usize) -> String {
    let mut curves: Vec<(&String, &CurveDef)> = curves_file.curves.iter().collect();
    curves.sort_by_key(|(name, _)| *name);

    let mut out = String::new();
    out.push_str("// Auto-generated by ph-curves-gen. Do not edit.\n\n");
    out.push_str("use ph_curves::{CurveLut, MonotonicCurveLut};\n\n");

    // Type aliases for convenience.
    out.push_str(&format!(
        "type Lut = CurveLut<{vt}, {vt}, {lut_size}>;\n",
        vt = value_type,
    ));
    out.push_str(&format!(
        "type MonoLut = MonotonicCurveLut<{vt}, {vt}, {lut_size}>;\n\n",
        vt = value_type,
    ));

    for (name, def) in &curves {
        let data = super::curve::build(name, def, lut_size);
        let const_name = to_const_name(name);
        emit_curve(
            &mut out,
            name,
            &const_name,
            def,
            &data,
            value_type,
            lut_size,
        );
    }

    out
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn emit_curve(
    out: &mut String,
    name: &str,
    const_name: &str,
    def: &CurveDef,
    data: &CurveData,
    value_type: &str,
    lut_size: usize,
) {
    // Forward LUT.
    out.push_str(&format!(
        "static {const_name}_FWD: [{vt}; {lut_size}] = {arr};\n",
        vt = value_type,
        arr = format_array(&data.fwd),
    ));

    // Inverse LUT (monotonic only).
    if let Some(inv) = &data.inv {
        out.push_str(&format!(
            "static {const_name}_INV: [{vt}; {lut_size}] = {arr};\n",
            vt = value_type,
            arr = format_array(inv),
        ));
    }

    // Public constant.
    if def.monotonic {
        out.push_str(&format!(
            "/// `{name}` \u{2014} monotonic curve.\n\
             pub const {const_name}: MonoLut = \
             MonoLut::new(&{const_name}_FWD, &{const_name}_INV);\n\n",
        ));
    } else {
        out.push_str(&format!(
            "/// `{name}` \u{2014} curve (non-monotonic).\n\
             pub const {const_name}: Lut = \
             Lut::new(&{const_name}_FWD, None);\n\n",
        ));
    }
}

fn to_const_name(name: &str) -> String {
    let mut out = String::new();
    let mut prev_underscore = false;
    for ch in name.chars() {
        let next = if ch.is_ascii_alphanumeric() {
            ch.to_ascii_uppercase()
        } else {
            '_'
        };
        if next == '_' {
            if !prev_underscore {
                out.push('_');
                prev_underscore = true;
            }
        } else {
            out.push(next);
            prev_underscore = false;
        }
    }
    if out.is_empty() {
        "CURVE".to_string()
    } else {
        out
    }
}

fn format_array(values: &[u32]) -> String {
    let mut out = String::from("[");
    for (idx, value) in values.iter().enumerate() {
        if idx > 0 {
            out.push_str(", ");
        }
        out.push_str(&value.to_string());
    }
    out.push(']');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    // ── to_const_name ─────────────────────────────────────────────

    #[test]
    fn const_name_simple() {
        assert_eq!(to_const_name("linear"), "LINEAR");
    }

    #[test]
    fn const_name_with_underscores() {
        assert_eq!(to_const_name("ease_in_quad"), "EASE_IN_QUAD");
    }

    #[test]
    fn const_name_collapses_multiple_non_alnum() {
        assert_eq!(to_const_name("a--b"), "A_B");
    }

    #[test]
    fn const_name_empty() {
        assert_eq!(to_const_name(""), "CURVE");
    }

    #[test]
    fn const_name_special_chars_only() {
        assert_eq!(to_const_name("---"), "_");
    }

    // ── format_array ──────────────────────────────────────────────

    #[test]
    fn format_array_small() {
        assert_eq!(format_array(&[0, 1, 2, 3]), "[0, 1, 2, 3]");
    }

    #[test]
    fn format_array_single() {
        assert_eq!(format_array(&[42]), "[42]");
    }

    #[test]
    fn format_array_empty() {
        assert_eq!(format_array(&[]), "[]");
    }

    // ── generate (integration) ────────────────────────────────────

    #[test]
    fn generate_monotonic_curve() {
        let mut curves = BTreeMap::new();
        curves.insert(
            "linear".to_string(),
            CurveDef {
                builtin: Some("linear".into()),
                formula: None,
                points: None,
                monotonic: true,
            },
        );
        let cf = CurvesFile { curves };
        let out = generate(&cf, "u8", 256);
        assert!(out.contains("AUTO_LINEAR_FWD") || out.contains("LINEAR_FWD"));
        assert!(out.contains("LINEAR_INV"));
        assert!(out.contains("MonoLut"));
    }

    #[test]
    fn generate_non_monotonic_curve() {
        let mut curves = BTreeMap::new();
        curves.insert(
            "wave".to_string(),
            CurveDef {
                builtin: None,
                formula: None,
                points: Some(vec![[0, 0], [64, 200], [192, 50], [255, 255]]),
                monotonic: false,
            },
        );
        let cf = CurvesFile { curves };
        let out = generate(&cf, "u8", 256);
        assert!(out.contains("WAVE_FWD"));
        assert!(!out.contains("WAVE_INV"));
        assert!(out.contains("Lut::new"));
    }

    #[test]
    fn generate_u16_lut() {
        let mut curves = BTreeMap::new();
        curves.insert(
            "lin".to_string(),
            CurveDef {
                builtin: Some("linear".into()),
                formula: None,
                points: None,
                monotonic: true,
            },
        );
        let cf = CurvesFile { curves };
        let out = generate(&cf, "u16", 10);
        assert!(out.contains("u16"));
        assert!(out.contains("10"));
    }
}
